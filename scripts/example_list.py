#!/usr/bin/env python3
"""Keep tests/common/examples.rs, the example corpus list, equal to the Lua
files under examples/.

The list is the corpus's only enumeration: every Rust consumer includes it,
the corpus gate expands it into one test per example, and no Rust code walks
examples/ (two `brokkr.toml` textlint rules guard that). A `brokkr check`
script check runs this in its default mode, so a new example, or a stray
untracked `.lua` file, fails the check until it is listed or removed.

Each entry is `name: "examples/<path>.lua",`. The name is the path below
examples/ without `.lua`, its directories joined by `_`
(`examples/calls/global.lua` is `calls_global`), and becomes the test's
name, so path components are limited to `[a-z0-9_]`, a name may not start
with a digit, be `_` or be a Rust keyword, and two paths may not map to one
name (`a/b.lua` and `a_b.lua`). Entries are in byte order of the path. A
symlink anywhere under examples/, or a `.lua` entry that is not a regular
file, fails the check: the corpus is regular files. The
list file must be exactly the generated text, since anything a lenient
parser skipped, Rust might still read.

`scripts/test_example_list.py` holds the fixture tests.

Usage:
  python3 scripts/example_list.py           compare the list with examples/; prints ok
  python3 scripts/example_list.py --write   rewrite the list from examples/
  python3 scripts/example_list.py --paths   print the listed paths, one per line
"""

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIST = Path("tests") / "common" / "examples.rs"

sys.path.insert(0, str(ROOT / "scripts"))
from write_if_changed import write_if_changed  # noqa: E402

HEADER = """\
// The example corpus: every Lua file under examples/, one entry per file as
// `name: "examples/<path>.lua",`, in byte order of the path. This list is the
// corpus's only enumeration; no Rust code walks examples/. Each includer
// defines an `examples!` macro taking `$($name:ident: $path:literal,)*` and
// then includes this file; the corpus gate expands it into one test per
// example, named by `name`.
//
// Generated by `python3 scripts/example_list.py --write`; the `example-list`
// script check in brokkr.toml fails while it differs from the files on disk.
"""

COMPONENT = re.compile(r"[a-z0-9_]+")
ENTRY_PATH = re.compile(r'^    [a-z0-9_]+: "([^"\n]*)",$', flags=re.MULTILINE)
RUST_KEYWORDS = {
    "abstract", "as", "async", "await", "become", "box", "break", "const",
    "continue", "crate", "do", "dyn", "else", "enum", "extern", "false",
    "final", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "macro",
    "match", "mod", "move", "mut", "override", "priv", "pub", "ref", "return",
    "self", "static", "struct", "super", "trait", "true", "try", "type",
    "typeof", "unsafe", "unsized", "use", "virtual", "where", "while", "yield",
}


class ListError(Exception):
    pass


def byte_order(paths):
    return sorted(paths, key=lambda path: path.encode("utf-8"))


def disk_paths(root):
    """Every `.lua` file under `root`/examples, as root-relative POSIX paths
    in byte order. Raises on a symlink or an unreadable directory."""
    examples = root / "examples"

    def fail(error):
        raise ListError(f"cannot read {error.filename}: {error.strerror}")

    if examples.is_symlink() or not examples.is_dir():
        raise ListError("examples/ is not a directory")
    paths = []
    for directory, subdirectories, files in os.walk(examples, onerror=fail):
        for entry in subdirectories + files:
            path = Path(directory) / entry
            if path.is_symlink():
                raise ListError(
                    f"{path.relative_to(root).as_posix()} is a symlink; the example corpus "
                    "is regular files"
                )
        for entry in files:
            path = Path(directory) / entry
            if entry.endswith(".lua"):
                # A FIFO or device would block the tests that read it.
                if not path.is_file():
                    raise ListError(
                        f"{path.relative_to(root).as_posix()} is not a regular file"
                    )
                paths.append(path.relative_to(root).as_posix())
    return byte_order(paths)


def name_for(path):
    """The test name of a root-relative example path."""
    parts = path.split("/")
    if parts[0] != "examples" or len(parts) < 2 or not parts[-1].endswith(".lua"):
        raise ListError(f"{path}: not a .lua file under examples/")
    parts = parts[1:-1] + [parts[-1][: -len(".lua")]]
    if not all(COMPONENT.fullmatch(part) for part in parts):
        raise ListError(f"{path}: path components below examples/ must match [a-z0-9_]+")
    name = "_".join(parts)
    if name == "_":
        raise ListError(f"{path}: `_` cannot name a test")
    if name[0].isdigit():
        raise ListError(f"{path}: its test name {name} starts with a digit")
    if name in RUST_KEYWORDS:
        raise ListError(f"{path}: its test name {name} is a Rust keyword")
    return name


def render(paths):
    """The canonical list file for `paths`."""
    if not paths:
        raise ListError("the example corpus is empty")
    if paths != byte_order(paths):
        raise ListError("example paths are not in byte order")
    entries = []
    seen = {}
    for path in paths:
        name = name_for(path)
        if name in seen:
            raise ListError(f"{seen[name]} and {path} both map to the test name {name}")
        seen[name] = path
        entries.append(f'    {name}: "{path}",\n')
    return HEADER + "examples! {\n" + "".join(entries) + "}\n"


def listed_paths(root):
    """The paths in the list file, which must be exactly its generated text."""
    try:
        text = (root / LIST).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise ListError(f"cannot read {LIST.as_posix()}: {error}")
    paths = ENTRY_PATH.findall(text)
    try:
        canonical = render(paths)
    except ListError as error:
        raise ListError(f"{LIST.as_posix()}: {error}")
    if text != canonical:
        raise ListError(
            f"{LIST.as_posix()} is not in the generated form; "
            "run python3 scripts/example_list.py --write"
        )
    return paths


def problems(root):
    """What differs between the list and the files on disk, or nothing."""
    on_disk = disk_paths(root)
    listed = listed_paths(root)
    if listed == on_disk:
        return []
    found = [f"not listed: {path}" for path in on_disk if path not in listed]
    found += [f"listed but not on disk: {path}" for path in listed if path not in on_disk]
    found.append("add or remove the example, then run python3 scripts/example_list.py --write")
    return found


def main(argv=None, root=ROOT):
    arguments = sys.argv[1:] if argv is None else argv
    try:
        if arguments == []:
            found = problems(root)
            for problem in found:
                print(problem)
            if found:
                return 1
            print("ok")
        elif arguments == ["--write"]:
            if write_if_changed(root / LIST, render(disk_paths(root)).encode("utf-8")):
                print(f"wrote {LIST.as_posix()}")
        elif arguments == ["--paths"]:
            for path in listed_paths(root):
                print(path)
        else:
            print("usage: python3 scripts/example_list.py [--write | --paths]", file=sys.stderr)
            return 2
    except ListError as error:
        print(error)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
