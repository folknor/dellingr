// The corpus cost golden, `tests/fixtures/corpus_cost.txt`: the `cost_used`
// of every listed example run once from a fresh State, as the CLI runs it.
// Shared by the corpus gate (`corpus::run_examples`, which reads the CLI's
// `Cost used: N` line and judges it here) and the `regenerate_corpus_cost`
// example, which writes the fixture.
//
// The first line names the cost model the costs were recorded under; each
// following line is `path|source|cost`, where `source` is the XXH3-128 digest
// of the example's bytes in hex. The digest separates the two reasons a cost
// can move: an edited example (regenerate the fixture) and a VM or compiler
// change to the cost of identical source, which is a cost model change and
// needs a `COST_MODEL_VERSION` bump first (`src/cost_meter.rs`). An edit to an
// example retires its old witness; the hand-written rows of
// `tests/fixtures/cost_golden.txt` are the cost model's exact record.

/// One recorded example.
pub(crate) struct Row {
    /// Its repository-relative path, as in `tests/common/examples.rs`.
    pub(crate) path: String,
    /// The XXH3-128 digest of its source bytes.
    pub(crate) source: u128,
    /// Its recorded `cost_used`.
    pub(crate) cost: u64,
}

/// The parsed fixture.
pub(crate) struct Fixture {
    /// The `COST_MODEL_VERSION` the costs were recorded under.
    pub(crate) cost_model: u16,
    /// One row per example, in list order.
    pub(crate) rows: Vec<Row>,
}

/// The digest a row records for an example's source bytes.
pub(crate) fn source_digest(source: &[u8]) -> u128 {
    xxhash_rust::xxh3::xxh3_128(source)
}

pub(crate) fn parse(text: &str) -> Result<Fixture, String> {
    let mut lines = text.lines();
    let header = lines.next().ok_or("the corpus cost fixture is empty")?;
    let malformed = || format!("first line {header:?} must be cost_model=<version>");
    let cost_model = header
        .strip_prefix("cost_model=")
        .ok_or_else(malformed)?
        .parse()
        .map_err(|_| malformed())?;
    let mut rows = Vec::new();
    for line in lines {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let fields: Vec<&str> = line.split('|').collect();
        let [path, source, cost] = fields[..] else {
            return Err(format!("malformed corpus cost row {line:?}"));
        };
        let source = u128::from_str_radix(source, 16)
            .map_err(|error| format!("{path}: bad source digest {source:?}: {error}"))?;
        let cost = cost
            .parse()
            .map_err(|error| format!("{path}: bad cost {cost:?}: {error}"))?;
        rows.push(Row {
            path: path.to_owned(),
            source,
            cost,
        });
    }
    Ok(Fixture { cost_model, rows })
}

pub(crate) fn render(fixture: &Fixture) -> String {
    let mut text = format!(
        "cost_model={}\n\
         # Generated by `brokkr run --release regenerate_corpus_cost -- tests/fixtures/corpus_cost.txt`.\n\
         # path|XXH3-128 of the source bytes|cost_used of one CLI run. See tests/common/corpus_cost_golden.rs.\n",
        fixture.cost_model
    );
    for row in &fixture.rows {
        text.push_str(&format!("{}|{:032x}|{}\n", row.path, row.source, row.cost));
    }
    text
}

const REGENERATE: &str = "regenerate it with `brokkr run --release regenerate_corpus_cost -- tests/fixtures/corpus_cost.txt`";

impl Fixture {
    /// Judges one example's observed cost against its recorded row.
    pub(crate) fn judge(
        &self,
        cost_model: u16,
        path: &str,
        source: u128,
        cost: u64,
    ) -> Result<(), String> {
        if self.cost_model != cost_model {
            return Err(format!(
                "tests/fixtures/corpus_cost.txt records cost model {}, COST_MODEL_VERSION is \
                 {cost_model}; {REGENERATE}",
                self.cost_model
            ));
        }
        let Some(row) = self.rows.iter().find(|row| row.path == path) else {
            return Err(format!(
                "{path} has no row in tests/fixtures/corpus_cost.txt; {REGENERATE}"
            ));
        };
        if row.source != source {
            return Err(format!(
                "{path} changed since its cost was recorded; review its cost ({cost}, was {}) and \
                 {REGENERATE}",
                row.cost
            ));
        }
        if row.cost != cost {
            return Err(format!(
                "{path}: identical source now costs {cost}, recorded {} under cost model \
                 {cost_model}. A changed cost for unchanged source is a cost model change: bump \
                 COST_MODEL_VERSION and document it in src/cost_meter.rs, then regenerate",
                row.cost
            ));
        }
        Ok(())
    }

    /// The rows of `replacement` that record a different cost for the same
    /// source under the same cost model: what a regeneration must refuse to
    /// bless.
    pub(crate) fn unversioned_changes(&self, replacement: &Fixture) -> Vec<String> {
        if self.cost_model != replacement.cost_model {
            return Vec::new();
        }
        replacement
            .rows
            .iter()
            .filter_map(|new| {
                let old = self
                    .rows
                    .iter()
                    .find(|old| old.path == new.path && old.source == new.source)?;
                (old.cost != new.cost)
                    .then(|| format!("{}: {} -> {}", new.path, old.cost, new.cost))
            })
            .collect()
    }
}
